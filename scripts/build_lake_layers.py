"""Build the lake background stack from the unpacked Cast n Chill level data.

The reference game stores each level's layer list inside a MonoBehaviour
(no typetree, so fields are unreadable) — but the *order* and the *names* are
plain serialized strings, and the name itself encodes the parallax:

    +<parallaxX>_<name>        e.g. "+70_far-mountains"
    +<parallaxX>_<parallaxY>_<name>
    -<parallaxX>_<name>

This script reads the layer list produced by `scripts/unpack_reference.py`
(`picnicpoint_layers.json`), copies the four time-of-day variants of every
layer into `projects/fishing/assets/sprites/bg/`, and writes
`projects/fishing/assets/lake_layers.json` in the format `world.rs` consumes.

Reference art is local-only (`.local/` and `projects/fishing/assets/sprites/`
are gitignored); run `scripts/gen_placeholder_sprites.py` for the shipped
placeholder set.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
from pathlib import Path

TODS = ["dawn", "day", "dusk", "night"]

# Name prefixes are parallax percentages. Far layers have a large positive
# value and move the least; foreground/underwater layers go negative.
def parallax_from_name(name: str) -> float:
    match = re.match(r"([+-]\d+)", name)
    if not match:
        return 0.5
    px = int(match.group(1))
    # Map [-40, +80] → [0.7, 0.05] so far layers drift slower than foreground.
    factor = (100.0 - px) / 200.0
    return max(0.0, min(1.0, factor))


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--reference", default=".local/reference/castnchill")
    parser.add_argument("--project", default="projects/fishing")
    args = parser.parse_args()

    reference = Path(args.reference)
    project = Path(args.project)

    layers_doc = json.loads((reference / "picnicpoint_layers.json").read_text(encoding="utf-8"))
    index = json.loads((reference / "index.json").read_text(encoding="utf-8"))

    # Layers are exported as Texture2D (the Sprite objects only carry the
    # rect/pivot); prefer the copies that came from the level bundle itself.
    by_name: dict[str, dict] = {}
    for entry in index:
        if entry.get("type") not in ("Sprite", "Texture2D") or not entry.get("path"):
            continue
        name = entry.get("name", "")
        if "picnicpoint" in entry.get("source", "") or name not in by_name:
            by_name[name] = entry

    out_dir = project / "assets" / "sprites" / "bg"
    out_dir.mkdir(parents=True, exist_ok=True)

    layers = []
    copied = 0
    missing = 0
    for order, name in enumerate(layers_doc["layers"]):
        variants = []
        for tod in TODS:
            entry = by_name.get(f"{name}@{tod}")
            if entry is None:
                missing += 1
                continue
            src = reference / entry["path"]
            dst = out_dir / f"{name}@{tod}.png"
            if src.is_file():
                shutil.copyfile(src, dst)
                copied += 1
            variants.append(f"bg/{name}@{tod}.png")
        if not variants:
            continue
        layers.append(
            {
                "slug": name,
                "parallax": round(parallax_from_name(name), 3),
                "x": 0.0,
                "y": 0.0,
                "reflect": False,
                "order": order,
            }
        )

    doc = {
        "_comment": (
            "Generated by scripts/build_lake_layers.py from the unpacked "
            "lake1-spot1-picnicpoint layer list. Array order = draw order "
            "(far -> near). Every layer is bottom-anchored at y=0 with a "
            "(0.5, 0) pivot, matching the reference sprites' own pivot."
        ),
        "camera_origin": [0.0, 180.0],
        "water_line": 80.0,
        "time_of_day": TODS,
        "layers": layers,
    }
    (project / "assets" / "lake_layers.json").write_text(
        json.dumps(doc, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    print(f"layers={len(layers)} copied={copied} missing_variants={missing}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
